#!/bin/sh
#
# lnd-artifacts — transport for per-project AI artifacts.
#
# The artifact store is a private git clone living in the host repository's git
# common dir (<git-common-dir>/lundegaard). Every first-level entry of the store
# root except .git is symlinked into the current worktree root and ignored via a
# marker-delimited block in <git-common-dir>/info/exclude.
#
# This script NEVER mutates the host repository: no commits, no staging, no
# config writes. It only touches the store, the symlinks, and the exclude block.
#
# POSIX shell + git + coreutils only. No `local`, no bashisms, no arrays.
#
set -eu

PROG=lnd-artifacts
VERSION=0.1.0

# --- globals ---------------------------------------------------------------

DRY_RUN=0
QUIET=0
ALL_WORKTREES=0
CHANGED=0

COMMON_DIR=""
STORE=""
EXCLUDE_FILE=""
WT_ROOT=""
LOCK_DIR=""
LOCK_HELD=0

EXCL_BEGIN='# >>> lnd-artifacts managed >>>'
EXCL_NOTE='# regenerated by lnd-artifacts — do not edit between these markers'
EXCL_END='# <<< lnd-artifacts managed <<<'

# Git environment inherited from a caller (e.g. a git hook) would silently
# redirect every store operation. Resolve everything from the working directory.
unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY 2>/dev/null || true

# --- output ----------------------------------------------------------------

say() { printf '%s\n' "$*"; }
info() { if [ "$QUIET" -eq 0 ]; then printf '%s\n' "$*"; fi; }
warn() { printf '%s: %s\n' "$PROG" "$*" >&2; }
die() { printf '%s: %s\n' "$PROG" "$*" >&2; exit 1; }

# report <action words...> — announce a mutation and count it.
report() {
    CHANGED=$((CHANGED + 1))
    if [ "$DRY_RUN" -eq 1 ]; then
        printf '  would %s\n' "$*"
    else
        printf '  %s\n' "$*"
    fi
}

# dry — true when running in --dry-run mode. Used as `dry || <mutation>`.
dry() { [ "$DRY_RUN" -eq 1 ]; }

usage() {
    cat <<EOF
$PROG $VERSION — per-project AI artifact transport

usage: $PROG <verb> [args] [options]

verbs:
  init <remote-url>   clone the artifact repo into <git-common-dir>/lundegaard
                      and link its first-level entries into this worktree
  heal                idempotent self-repair of links and the exclude block
  adopt <path>        move an untracked first-level path into the store and
                      link it back
  sync                commit everything in the store, pull --rebase, push
  status              report store, sync and link health (never mutates)
  cure                remove managed links and the exclude block; keep the store

options:
  --dry-run           print the full plan, change nothing
  --quiet             suppress output when nothing changed (heal)
  -m, --message MSG   commit message for sync
  --all-worktrees     cure: also unlink every other worktree of this clone
  -h, --help          this text
  -V, --version       print version
EOF
}

# --- path helpers ----------------------------------------------------------

# canon <path> — fully resolved physical path of an existing path (follows
# symlinks). Fails when the path does not exist or its parent is unreachable.
canon() {
    if [ -d "$1" ]; then
        (cd "$1" && pwd -P)
        return 0
    fi
    cn_p=$1
    cn_n=0
    while [ "$cn_n" -lt 40 ]; do
        cn_d=$(dirname "$cn_p")
        cn_b=$(basename "$cn_p")
        cn_d=$(cd "$cn_d" 2>/dev/null && pwd -P) || return 1
        cn_p="$cn_d/$cn_b"
        if [ -L "$cn_p" ]; then
            cn_t=$(readlink "$cn_p")
            case $cn_t in
                /*) cn_p=$cn_t ;;
                *) cn_p="$cn_d/$cn_t" ;;
            esac
            if [ -d "$cn_p" ]; then
                (cd "$cn_p" && pwd -P)
                return 0
            fi
            cn_n=$((cn_n + 1))
            continue
        fi
        if [ -e "$cn_p" ]; then
            printf '%s\n' "$cn_p"
            return 0
        fi
        return 1
    done
    return 1
}

# lexnorm <abs-path> — resolve . and .. textually (works for missing paths).
lexnorm() {
    lx_in=$1
    lx_out=""
    lx_oifs=$IFS
    IFS=/
    set -f
    for lx_c in $lx_in; do
        case $lx_c in
            '' | .) continue ;;
            ..) lx_out=${lx_out%/*} ;;
            *) lx_out="$lx_out/$lx_c" ;;
        esac
    done
    set +f
    IFS=$lx_oifs
    if [ -z "$lx_out" ]; then
        printf '/\n'
    else
        printf '%s\n' "$lx_out"
    fi
}

# relpath <target-abs> <base-dir-abs> — relative path from base to target.
relpath() {
    rp_t=${1%/}
    rp_b=${2%/}
    if [ -z "$rp_t" ]; then rp_t=/; fi
    if [ "$rp_b" = "/" ]; then rp_b=""; fi
    rp_up=""
    rp_rest=""
    while :; do
        if [ "$rp_t" = "$rp_b" ]; then
            rp_rest=""
            break
        fi
        case $rp_t in
            "$rp_b"/*)
                rp_rest=${rp_t#"$rp_b"/}
                break
                ;;
        esac
        rp_b=$(dirname "$rp_b")
        if [ "$rp_b" = "/" ]; then rp_b=""; fi
        if [ -z "$rp_up" ]; then rp_up=".."; else rp_up="../$rp_up"; fi
    done
    if [ -z "$rp_up" ] && [ -z "$rp_rest" ]; then
        printf '.\n'
    elif [ -z "$rp_up" ]; then
        printf '%s\n' "$rp_rest"
    elif [ -z "$rp_rest" ]; then
        printf '%s\n' "$rp_up"
    else
        printf '%s/%s\n' "$rp_up" "$rp_rest"
    fi
}

# --- store resolution (artifact-store) -------------------------------------

resolve_repo() {
    if ! git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
        die "not inside a git working tree — $PROG needs a git repository (run it from your project)"
    fi
    COMMON_DIR=$(git rev-parse --git-common-dir)
    case $COMMON_DIR in
        /*) ;;
        *) COMMON_DIR="$PWD/$COMMON_DIR" ;;
    esac
    COMMON_DIR=$(cd "$COMMON_DIR" && pwd -P) ||
        die "cannot resolve the git common dir"
    STORE="$COMMON_DIR/lundegaard"
    EXCLUDE_FILE="$COMMON_DIR/info/exclude"
    # The lock is a sibling of the store, not a store-root entry: anything at the
    # store root gets symlinked into the project (D2) and swept up by `sync`'s
    # commit -A. The common dir is shared by every worktree of the clone, so the
    # lock still serializes them all (D5's actual requirement).
    LOCK_DIR="$COMMON_DIR/lundegaard.lock"
    WT_ROOT=$(git rev-parse --show-toplevel)
    WT_ROOT=$(cd "$WT_ROOT" && pwd -P) ||
        die "cannot resolve the worktree root"
}

require_store() {
    if [ ! -d "$STORE" ]; then
        die "no artifact store at $STORE — run '$PROG init <remote-url>' first"
    fi
}

# --- locking ---------------------------------------------------------------

release_lock() {
    if [ "$LOCK_HELD" -eq 1 ]; then
        rm -rf "$LOCK_DIR"
        LOCK_HELD=0
    fi
}

acquire_lock() {
    if dry; then return 0; fi
    al_i=0
    while [ "$al_i" -lt 10 ]; do
        if mkdir "$LOCK_DIR" 2>/dev/null; then
            LOCK_HELD=1
            trap 'release_lock' EXIT
            trap 'release_lock; exit 130' INT
            trap 'release_lock; exit 143' TERM
            trap 'release_lock; exit 129' HUP
            {
                printf 'pid=%s\n' "$$"
                printf 'started=%s\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')"
                printf 'verb=%s\n' "${VERB:-?}"
            } >"$LOCK_DIR/owner" 2>/dev/null || true
            return 0
        fi
        al_i=$((al_i + 1))
        if [ "$al_i" -lt 10 ]; then sleep 1; fi
    done

    al_pid=""
    if [ -f "$LOCK_DIR/owner" ]; then
        al_pid=$(sed -n 's/^pid=//p' "$LOCK_DIR/owner" 2>/dev/null || true)
    fi
    if [ -n "$al_pid" ] && ! kill -0 "$al_pid" 2>/dev/null; then
        die "store lock $LOCK_DIR is held by pid $al_pid, which is no longer running.
If no other $PROG is active, remove it: rm -rf '$LOCK_DIR'"
    fi
    die "could not acquire the store lock $LOCK_DIR (held by pid ${al_pid:-unknown}); another $PROG run is in progress"
}

# --- store listing (artifact-linking) --------------------------------------

# store_entries — first-level store entries except .git, one per line, sorted.
store_entries() {
    if [ ! -d "$STORE" ]; then return 0; fi
    (
        cd "$STORE" || exit 0
        for se_e in * .[!.]* ..?*; do
            if [ ! -e "$se_e" ] && [ ! -L "$se_e" ]; then continue; fi
            if [ "$se_e" = ".git" ]; then continue; fi
            printf '%s\n' "$se_e"
        done
    ) | LC_ALL=C sort
}

# --- exclude block (D4) ----------------------------------------------------

has_block() {
    [ -f "$EXCLUDE_FILE" ] && grep -Fqx "$EXCL_BEGIN" "$EXCLUDE_FILE" 2>/dev/null
}

# read_managed — names currently listed inside the managed block.
read_managed() {
    if [ ! -f "$EXCLUDE_FILE" ]; then return 0; fi
    rd_inside=0
    while IFS= read -r rd_line || [ -n "$rd_line" ]; do
        if [ "$rd_line" = "$EXCL_BEGIN" ]; then
            rd_inside=1
            continue
        fi
        if [ "$rd_inside" -eq 1 ] && [ "$rd_line" = "$EXCL_END" ]; then
            rd_inside=0
            continue
        fi
        if [ "$rd_inside" -eq 1 ]; then
            case $rd_line in
                '' | '#'*) continue ;;
                '\'*) rd_line=${rd_line#\\} ;;
            esac
            printf '%s\n' "${rd_line#/}"
        fi
    done <"$EXCLUDE_FILE"
}

# emit_block <newline-separated-names>
emit_block() {
    printf '%s\n%s\n' "$EXCL_BEGIN" "$EXCL_NOTE"
    printf '%s\n' "$1" | while IFS= read -r eb_n; do
        if [ -z "$eb_n" ]; then continue; fi
        case $eb_n in
            '#'* | '!'*) printf '/\\%s\n' "$eb_n" ;;
            *) printf '/%s\n' "$eb_n" ;;
        esac
    done
    printf '%s\n' "$EXCL_END"
}

# write_exclude <newline-separated-names> — rewrite the managed block in place,
# preserving everything outside the markers. Empty input removes the block.
write_exclude() {
    we_entries=$1
    if [ -z "$we_entries" ]; then
        remove_exclude
        return 0
    fi
    we_dir=$(dirname "$EXCLUDE_FILE")
    if [ ! -d "$we_dir" ]; then mkdir -p "$we_dir"; fi
    we_tmp="$EXCLUDE_FILE.lnd-tmp.$$"
    : >"$we_tmp"
    we_seen=0
    if [ -f "$EXCLUDE_FILE" ]; then
        we_inside=0
        while IFS= read -r we_line || [ -n "$we_line" ]; do
            if [ "$we_line" = "$EXCL_BEGIN" ]; then
                we_inside=1
                we_seen=1
                emit_block "$we_entries" >>"$we_tmp"
                continue
            fi
            if [ "$we_inside" -eq 1 ]; then
                if [ "$we_line" = "$EXCL_END" ]; then we_inside=0; fi
                continue
            fi
            printf '%s\n' "$we_line" >>"$we_tmp"
        done <"$EXCLUDE_FILE"
    fi
    if [ "$we_seen" -eq 0 ]; then
        emit_block "$we_entries" >>"$we_tmp"
    fi
    mv "$we_tmp" "$EXCLUDE_FILE"
}

remove_exclude() {
    if [ ! -f "$EXCLUDE_FILE" ]; then return 0; fi
    if ! has_block; then return 0; fi
    rx_tmp="$EXCLUDE_FILE.lnd-tmp.$$"
    : >"$rx_tmp"
    rx_inside=0
    while IFS= read -r rx_line || [ -n "$rx_line" ]; do
        if [ "$rx_line" = "$EXCL_BEGIN" ]; then
            rx_inside=1
            continue
        fi
        if [ "$rx_inside" -eq 1 ]; then
            if [ "$rx_line" = "$EXCL_END" ]; then rx_inside=0; fi
            continue
        fi
        printf '%s\n' "$rx_line" >>"$rx_tmp"
    done <"$EXCLUDE_FILE"
    mv "$rx_tmp" "$EXCLUDE_FILE"
}

# sync_exclude <newline-separated-names> — rewrite only when the block differs.
sync_exclude() {
    sx_want=$1
    sx_have=$(read_managed)
    if [ "$sx_want" = "$sx_have" ]; then
        if [ -z "$sx_want" ] || has_block; then
            return 0
        fi
    fi
    if [ -z "$sx_want" ]; then
        report "remove managed block from $EXCLUDE_FILE"
    else
        report "update managed block in $EXCLUDE_FILE"
    fi
    dry || write_exclude "$sx_want"
}

# --- link helpers (D2, D3) -------------------------------------------------

# link_into_store <path> — true when <path> is a symlink resolving into the
# store (textually, so broken links still count as ours).
link_into_store() {
    lis_t=$(readlink "$1" 2>/dev/null) || return 1
    case $lis_t in
        /*) lis_abs=$lis_t ;;
        *) lis_abs="$(dirname "$1")/$lis_t" ;;
    esac
    lis_abs=$(lexnorm "$lis_abs")
    case $lis_abs in
        "$STORE" | "$STORE"/*) return 0 ;;
    esac
    return 1
}

# host_tracks <name> — true when the host repository tracks this first-level path.
host_tracks() {
    [ -n "$(git -C "$WT_ROOT" ls-files -- "$1" 2>/dev/null)" ]
}

# quarantine <name> — rename a foreign path out of the way, never delete.
quarantine() {
    qr_name=$1
    qr_ts=$(date '+%Y%m%d%H%M%S')
    qr_new="$qr_name.quarantined-$qr_ts"
    qr_i=0
    while [ -e "$WT_ROOT/$qr_new" ] || [ -L "$WT_ROOT/$qr_new" ]; do
        qr_i=$((qr_i + 1))
        qr_new="$qr_name.quarantined-$qr_ts-$qr_i"
    done
    report "QUARANTINE $qr_name -> $qr_new (pre-existing, not deleted)"
    dry || mv "$WT_ROOT/$qr_name" "$WT_ROOT/$qr_new"
}

# skip_tracked <name> — refuse to move a path the host repository tracks.
# Quarantining tracked content would show up as a deletion in the customer's
# repository, which this tool must never cause.
skip_tracked() {
    if ! host_tracks "$1"; then return 1; fi
    warn "skipped '$1': the host repository tracks it, and the store also provides an
  entry with that name. Nothing was moved — customer content wins. Rename the store
  entry ($STORE/$1) or drop it from the store to resolve the collision."
    return 0
}

# ensure_link <name> — make $WT_ROOT/<name> a correct relative symlink to the
# store entry, quarantining whatever foreign thing sits there.
ensure_link() {
    el_name=$1
    el_src="$STORE/$el_name"
    el_dst="$WT_ROOT/$el_name"
    el_want=$(relpath "$el_src" "$WT_ROOT")

    if [ -L "$el_dst" ]; then
        el_have=$(canon "$el_dst" 2>/dev/null || true)
        el_expect=$(canon "$el_src" 2>/dev/null || true)
        if [ -n "$el_have" ] && [ "$el_have" = "$el_expect" ]; then
            return 0
        fi
        if link_into_store "$el_dst"; then
            report "relink $el_name -> $el_want"
            dry || {
                rm -f "$el_dst"
                ln -s "$el_want" "$el_dst"
            }
            return 0
        fi
        if skip_tracked "$el_name"; then return 0; fi
        quarantine "$el_name"
    elif [ -e "$el_dst" ]; then
        if skip_tracked "$el_name"; then return 0; fi
        quarantine "$el_name"
    fi

    report "link $el_name -> $el_want"
    dry || ln -s "$el_want" "$el_dst"
}

# unlink_managed <name> — remove a managed link (only ever a symlink into the
# store); report anything else and leave it alone.
unlink_managed() {
    um_name=$1
    um_dst="$WT_ROOT/$um_name"
    if [ ! -L "$um_dst" ]; then
        # A real path here was never ours — heal already warned about the
        # collision if the host tracks it.
        if [ -e "$um_dst" ] && ! host_tracks "$um_name"; then
            warn "left $um_name alone: not a symlink into the store"
        fi
        return 0
    fi
    if host_tracks "$um_name"; then
        warn "left $um_name alone: the host repository tracks it"
        return 0
    fi
    if link_into_store "$um_dst"; then
        report "unlink $um_name"
        dry || rm -f "$um_dst"
        return 0
    fi
    warn "left $um_name alone: symlink does not point into the store"
    return 0
}

# --- heal (3.2) ------------------------------------------------------------

do_heal() {
    dh_entries=$(store_entries)

    # Drop links whose store entry disappeared. The managed block is the record
    # of what we linked last time.
    dh_managed=$(read_managed)
    if [ -n "$dh_managed" ]; then
        dh_oifs=$IFS
        IFS='
'
        set -f
        # shellcheck disable=SC2086
        set -- $dh_managed
        set +f
        IFS=$dh_oifs
        for dh_old in "$@"; do
            if printf '%s\n' "$dh_entries" | grep -Fqx -- "$dh_old"; then continue; fi
            unlink_managed "$dh_old"
        done
    fi

    if [ -n "$dh_entries" ]; then
        dh_oifs=$IFS
        IFS='
'
        set -f
        # shellcheck disable=SC2086
        set -- $dh_entries
        set +f
        IFS=$dh_oifs
        for dh_e in "$@"; do
            ensure_link "$dh_e"
        done
    fi

    sync_exclude "$dh_entries"
}

heal_summary() {
    hs_n=$(store_entries | grep -c . || true)
    if [ "$CHANGED" -eq 0 ]; then
        info "$PROG: healthy — $hs_n link(s) up to date in $WT_ROOT"
    elif dry; then
        say "$PROG: $CHANGED change(s) planned (dry run, nothing written)"
    else
        say "$PROG: healed — $CHANGED change(s) in $WT_ROOT"
    fi
}

cmd_heal() {
    resolve_repo
    require_store
    acquire_lock
    do_heal
    release_lock
    heal_summary
}

# --- init (3.1) ------------------------------------------------------------

cmd_init() {
    ci_url=${1:-}
    if [ -z "$ci_url" ]; then
        usage >&2
        die "init needs the artifact repository remote URL"
    fi
    resolve_repo
    if [ -e "$STORE" ]; then
        die "an artifact store already exists at $STORE — use '$PROG status' or '$PROG heal'"
    fi

    if dry; then
        say "$PROG: init plan"
        report "clone $ci_url -> $STORE"
        report "link every first-level store entry (except .git) into $WT_ROOT"
        report "write the managed block to $EXCLUDE_FILE"
        say "$PROG: $CHANGED change(s) planned (dry run, nothing written)"
        return 0
    fi

    acquire_lock
    say "$PROG: cloning $ci_url"
    if ! git clone -- "$ci_url" "$STORE"; then
        rm -rf "$STORE"
        die "clone failed — no store was created"
    fi
    CHANGED=$((CHANGED + 1))
    do_heal
    release_lock
    say "$PROG: store ready at $STORE"
    ci_n=$(store_entries | grep -c . || true)
    if [ "$ci_n" = "0" ]; then
        say "$PROG: the store is empty — add artifacts inside $STORE (or use '$PROG adopt <path>')"
    fi
}

# --- adopt (3.3) -----------------------------------------------------------

cmd_adopt() {
    ca_arg=${1:-}
    if [ -z "$ca_arg" ]; then
        usage >&2
        die "adopt needs a path"
    fi
    resolve_repo
    require_store

    # Only first-level entries of the current worktree root.
    ca_abs=$ca_arg
    case $ca_abs in
        /*) ;;
        *) ca_abs="$PWD/$ca_abs" ;;
    esac
    ca_abs=$(lexnorm "$ca_abs")
    ca_abs=${ca_abs%/}
    ca_name=$(basename "$ca_abs")
    ca_parent=$(dirname "$ca_abs")
    ca_parent=$(cd "$ca_parent" 2>/dev/null && pwd -P) ||
        die "cannot resolve $ca_arg"
    if [ "$ca_parent" != "$WT_ROOT" ]; then
        die "adopt only takes first-level entries of the worktree root ($WT_ROOT); '$ca_arg' lives in $ca_parent"
    fi
    ca_path="$WT_ROOT/$ca_name"

    if [ ! -e "$ca_path" ] && [ ! -L "$ca_path" ]; then
        die "$ca_name does not exist in $WT_ROOT"
    fi
    if [ -L "$ca_path" ] && link_into_store "$ca_path"; then
        die "$ca_name is already a managed link into the store"
    fi
    if [ -e "$STORE/$ca_name" ] || [ -L "$STORE/$ca_name" ]; then
        die "the store already contains '$ca_name' — resolve the collision by hand in $STORE"
    fi
    if [ "$ca_name" = ".git" ]; then
        die "refusing to adopt .git"
    fi
    if [ -n "$(git -C "$WT_ROOT" ls-files -- "$ca_name" 2>/dev/null)" ]; then
        die "'$ca_name' is tracked by the host repository — tracked content belongs to the customer repo and adopting it would require a deletion commit there"
    fi

    say "$PROG: adopting $ca_name"
    if dry; then
        report "move $ca_path -> $STORE/$ca_name"
        report "link $ca_name -> $(relpath "$STORE/$ca_name" "$WT_ROOT")"
        report "add /$ca_name to the managed block in $EXCLUDE_FILE"
        say "$PROG: $CHANGED change(s) planned (dry run, nothing written)"
        return 0
    fi

    acquire_lock
    report "move $ca_path -> $STORE/$ca_name"
    mv "$ca_path" "$STORE/$ca_name"
    ensure_link "$ca_name"
    sync_exclude "$(store_entries)"
    release_lock
    say "$PROG: adopted $ca_name — commit it with '$PROG sync'"
}

# --- sync (3.4) ------------------------------------------------------------

store_git() { git -C "$STORE" "$@"; }

store_branch() { store_git symbolic-ref --quiet --short HEAD 2>/dev/null || printf 'HEAD\n'; }

store_upstream() { store_git rev-parse --abbrev-ref --symbolic-full-name '@{u}' 2>/dev/null || true; }

cmd_sync() {
    cs_msg=${SYNC_MESSAGE:-}
    resolve_repo
    require_store

    cs_dirty=$(store_git status --porcelain | grep -c . || true)
    cs_up=$(store_upstream)
    cs_ahead=0
    if [ -n "$cs_up" ]; then
        cs_ahead=$(store_git rev-list --count '@{u}..HEAD' 2>/dev/null || printf '0')
    fi

    if [ "$cs_dirty" = "0" ] && [ "$cs_ahead" = "0" ] && [ -n "$cs_up" ]; then
        say "$PROG: already in sync — nothing to commit, nothing to push"
        return 0
    fi
    if [ "$cs_dirty" = "0" ] && ! store_git rev-parse --verify --quiet HEAD >/dev/null 2>&1; then
        say "$PROG: the store is empty and has no commits — nothing to sync"
        return 0
    fi

    if [ -z "$cs_msg" ]; then
        cs_msg="artifacts: sync $(date '+%Y-%m-%d %H:%M:%S')"
    fi

    if dry; then
        say "$PROG: sync plan for $STORE"
        if [ "$cs_dirty" != "0" ]; then
            report "commit $cs_dirty change(s) with message: $cs_msg"
        fi
        if [ -n "$cs_up" ]; then
            report "pull --rebase from $cs_up"
            report "push to $cs_up"
        else
            report "push and set upstream (branch $(store_branch) has none)"
        fi
        say "$PROG: $CHANGED change(s) planned (dry run, nothing written)"
        return 0
    fi

    acquire_lock

    if [ "$cs_dirty" != "0" ]; then
        report "commit $cs_dirty change(s)"
        store_git add -A
        store_git commit -q -m "$cs_msg"
    fi

    cs_branch=$(store_branch)
    if [ -z "$cs_up" ]; then
        if [ -z "$(store_git remote 2>/dev/null)" ]; then
            release_lock
            say "$PROG: committed locally; the store has no remote, so nothing was pushed"
            return 0
        fi
        report "push -u origin $cs_branch"
        if ! store_git push -u origin "$cs_branch"; then
            release_lock
            die "push failed — the store is at $STORE"
        fi
        release_lock
        say "$PROG: pushed $(store_git rev-parse --short HEAD) to origin/$cs_branch"
        return 0
    fi

    report "pull --rebase"
    if ! store_git pull --rebase --quiet; then
        cs_conf=$(store_git diff --name-only --diff-filter=U 2>/dev/null || true)
        warn "rebase stopped in the artifact store: $STORE"
        if [ -n "$cs_conf" ]; then
            warn "conflicted paths:"
            printf '%s\n' "$cs_conf" | sed 's/^/  /' >&2
        fi
        warn "resolve them there (git -C '$STORE' status), then run '$PROG sync' again"
        release_lock
        exit 1
    fi

    report "push"
    if ! store_git push --quiet; then
        release_lock
        die "push failed — the store is at $STORE"
    fi
    release_lock
    say "$PROG: pushed $(store_git rev-parse --short HEAD) to $cs_up"
}

# --- status (3.5) ----------------------------------------------------------

cmd_status() {
    resolve_repo

    say "$PROG $VERSION"
    say "  worktree : $WT_ROOT"
    say "  store    : $STORE"

    if [ ! -d "$STORE" ]; then
        say "  state    : no store initialized — run '$PROG init <remote-url>'"
        return 0
    fi

    ct_dirty=$(store_git status --porcelain 2>/dev/null | grep -c . || true)
    ct_up=$(store_upstream)
    ct_branch=$(store_branch)
    ct_ahead=0
    ct_behind=0
    if [ -n "$ct_up" ]; then
        ct_ahead=$(store_git rev-list --count '@{u}..HEAD' 2>/dev/null || printf '0')
        ct_behind=$(store_git rev-list --count 'HEAD..@{u}' 2>/dev/null || printf '0')
    fi

    say "  branch   : $ct_branch${ct_up:+ (upstream $ct_up)}"
    if [ -z "$ct_up" ]; then
        say "  remote   : no upstream configured for $ct_branch"
    fi
    say "  dirty    : $ct_dirty file(s) uncommitted"
    say "  unpushed : $ct_ahead commit(s)"
    say "  behind   : $ct_behind commit(s) (as of the last fetch; status never fetches)"

    ct_entries=$(store_entries)
    ct_total=$(printf '%s\n' "$ct_entries" | grep -c . || true)
    say "  links    : $ct_total managed entry(ies)"

    ct_bad=0
    if [ -n "$ct_entries" ]; then
        ct_oifs=$IFS
        IFS='
'
        set -f
        # shellcheck disable=SC2086
        set -- $ct_entries
        set +f
        IFS=$ct_oifs
        for ct_e in "$@"; do
            ct_dst="$WT_ROOT/$ct_e"
            if [ ! -L "$ct_dst" ] && [ ! -e "$ct_dst" ]; then
                say "    MISSING      $ct_e"
                ct_bad=$((ct_bad + 1))
            elif [ ! -L "$ct_dst" ]; then
                if host_tracks "$ct_e"; then
                    say "    COLLISION    $ct_e (tracked by the host repo; the store entry cannot be linked)"
                else
                    say "    NOT-A-LINK   $ct_e (real file or directory in the way)"
                fi
                ct_bad=$((ct_bad + 1))
            else
                ct_have=$(canon "$ct_dst" 2>/dev/null || true)
                ct_expect=$(canon "$STORE/$ct_e" 2>/dev/null || true)
                if [ -z "$ct_have" ] || [ "$ct_have" != "$ct_expect" ]; then
                    say "    WRONG-TARGET $ct_e"
                    ct_bad=$((ct_bad + 1))
                fi
            fi
        done
    fi
    if [ "$ct_bad" -eq 0 ] && [ "$ct_total" != "0" ]; then
        say "    all links healthy in this worktree"
    fi
    if [ "$ct_bad" -ne 0 ]; then
        say "    -> run '$PROG heal' to repair"
    fi

    if ! has_block && [ "$ct_total" != "0" ]; then
        say "  exclude  : managed block MISSING from $EXCLUDE_FILE -> run '$PROG heal'"
    fi

    ct_q=$(
        cd "$WT_ROOT" 2>/dev/null || exit 0
        for ct_f in *.quarantined-* .*.quarantined-*; do
            if [ -e "$ct_f" ] || [ -L "$ct_f" ]; then printf '%s\n' "$ct_f"; fi
        done
    )
    if [ -n "$ct_q" ]; then
        say "  quarantine leftovers in this worktree:"
        printf '%s\n' "$ct_q" | sed 's/^/    /'
    fi

    ct_susp=$(
        printf '%s\n' "$ct_entries" |
            grep -Ex '(README|readme|README\.md|readme\.md|LICENSE|LICENSE\.md|\.gitignore|\.gitattributes)' || true
    )
    if [ -n "$ct_susp" ]; then
        say "  WARNING: the store root should be payload-only; these entries get symlinked"
        say "           into the project root and probably do not belong there:"
        printf '%s\n' "$ct_susp" | sed 's/^/    /'
    fi

    if [ "$ct_dirty" != "0" ] || [ "$ct_ahead" != "0" ]; then
        say "  -> unsynced artifact work: run '$PROG sync'"
    fi
    return 0
}

# --- cure (3.6) ------------------------------------------------------------

cure_worktree() {
    cw_root=$1
    cw_names=$2
    cw_save=$WT_ROOT
    WT_ROOT=$cw_root
    say "$PROG: unlinking in $cw_root"
    cw_oifs=$IFS
    IFS='
'
    set -f
    # shellcheck disable=SC2086
    set -- $cw_names
    set +f
    IFS=$cw_oifs
    for cw_n in "$@"; do
        unlink_managed "$cw_n"
    done
    WT_ROOT=$cw_save
}

cmd_cure() {
    resolve_repo
    require_store

    cc_names=$(read_managed)
    if [ -z "$cc_names" ]; then
        cc_names=$(store_entries)
    fi
    if [ -z "$cc_names" ]; then
        say "$PROG: nothing managed here — no links or exclude block to remove"
        return 0
    fi

    if ! dry; then acquire_lock; fi

    cure_worktree "$WT_ROOT" "$cc_names"

    cc_others=$(
        git worktree list --porcelain 2>/dev/null |
            sed -n 's/^worktree //p' || true
    )
    cc_rest=""
    if [ -n "$cc_others" ]; then
        cc_oifs=$IFS
        IFS='
'
        set -f
        # shellcheck disable=SC2086
        set -- $cc_others
        set +f
        IFS=$cc_oifs
        for cc_w in "$@"; do
            cc_wp=$(cd "$cc_w" 2>/dev/null && pwd -P) || cc_wp=""
            if [ -z "$cc_wp" ] || [ "$cc_wp" = "$WT_ROOT" ]; then continue; fi
            if [ "$ALL_WORKTREES" -eq 1 ]; then
                cure_worktree "$cc_wp" "$cc_names"
            else
                cc_rest="${cc_rest}${cc_rest:+
}$cc_wp"
            fi
        done
    fi

    sync_exclude ""

    if ! dry; then release_lock; fi

    if [ -n "$cc_rest" ]; then
        say "$PROG: other worktrees of this clone still carry managed links:"
        printf '%s\n' "$cc_rest" | sed 's/^/    /'
        say "         re-run with --all-worktrees to unlink them too"
    fi
    if dry; then
        say "$PROG: $CHANGED change(s) planned (dry run, nothing written)"
    else
        say "$PROG: cured — $CHANGED change(s); the store at $STORE is untouched ('$PROG heal' restores everything)"
    fi
}

# --- dispatch (2.1) --------------------------------------------------------

VERB=""
SYNC_MESSAGE=""
ARG1=""

main() {
    if [ "$#" -eq 0 ]; then
        usage >&2
        exit 1
    fi

    while [ "$#" -gt 0 ]; do
        case $1 in
            --dry-run | -n)
                DRY_RUN=1
                ;;
            --quiet | -q)
                QUIET=1
                ;;
            --all-worktrees)
                ALL_WORKTREES=1
                ;;
            -m | --message)
                if [ "$#" -lt 2 ]; then die "$1 needs a value"; fi
                shift
                SYNC_MESSAGE=$1
                ;;
            -h | --help | help)
                usage
                exit 0
                ;;
            -V | --version)
                say "$PROG $VERSION"
                exit 0
                ;;
            --)
                shift
                while [ "$#" -gt 0 ]; do
                    if [ -z "$VERB" ]; then VERB=$1; elif [ -z "$ARG1" ]; then ARG1=$1; fi
                    shift
                done
                break
                ;;
            -*)
                usage >&2
                die "unknown option: $1"
                ;;
            *)
                if [ -z "$VERB" ]; then
                    VERB=$1
                elif [ -z "$ARG1" ]; then
                    ARG1=$1
                else
                    usage >&2
                    die "unexpected argument: $1"
                fi
                ;;
        esac
        shift
    done

    if [ -z "$VERB" ]; then
        usage >&2
        die "no verb given"
    fi

    case $VERB in
        init) cmd_init "$ARG1" ;;
        heal) cmd_heal ;;
        adopt) cmd_adopt "$ARG1" ;;
        sync) cmd_sync ;;
        status) cmd_status ;;
        cure) cmd_cure ;;
        *)
            usage >&2
            die "unknown verb: $VERB"
            ;;
    esac
}

main "$@"
