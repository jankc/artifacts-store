#!/bin/sh
#
# lnd-artifacts — transport for per-project AI artifacts.
#
# The artifact store is a private git clone living in the host repository's git
# common dir (<git-common-dir>/lundegaard). Every first-level entry of the store
# root except .git is symlinked into the current worktree root and ignored via a
# marker-delimited block in <git-common-dir>/info/exclude.
#
# `init` and `heal` also keep a runnable copy of this script beside the store, at
# <git-common-dir>/lundegaard.engine.sh, so worktree-init tooling can bootstrap a
# new worktree without knowing where the plugin is installed.
#
# This script NEVER mutates the host repository: no commits, no staging, no
# config writes. It only touches the store, the symlinks, and the exclude block.
#
# POSIX shell + git + coreutils only. No `local`, no bashisms, no arrays.
#
set -eu

PROG=lnd-artifacts
VERSION=0.1.1

# Absolute path of the running script, captured before anything can change the
# working directory: it is the source of the vendored copy (B1/B2).
SELF=$0
case $SELF in
    /*) ;;
    *) SELF="$PWD/$SELF" ;;
esac

# --- globals ---------------------------------------------------------------

DRY_RUN=0
QUIET=0
ALL_WORKTREES=0
CHANGED=0

COMMON_DIR=""
STORE=""
EXCLUDE_FILE=""
WT_ROOT=""
LOCK_DIR=""
VENDORED_ENGINE=""
LOCK_HELD=0
INIT_PARTIAL=0

EXCL_BEGIN='# >>> lnd-artifacts managed >>>'
EXCL_NOTE='# regenerated by lnd-artifacts — do not edit between these markers'
EXCL_END='# <<< lnd-artifacts managed <<<'

# Git environment inherited from a caller (e.g. a git hook) would silently
# redirect every store operation. Resolve everything from the working directory.
unset GIT_DIR GIT_COMMON_DIR GIT_WORK_TREE GIT_INDEX_FILE GIT_OBJECT_DIRECTORY 2>/dev/null || true

# --- output ----------------------------------------------------------------

say() { printf '%s\n' "$*"; }
info() { if [ "$QUIET" -eq 0 ]; then printf '%s\n' "$*"; fi; }
warn() { printf '%s: %s\n' "$PROG" "$*" >&2; }
die() { printf '%s: %s\n' "$PROG" "$*" >&2; exit 1; }

# report <action words...> — announce a mutation and count it.
report() {
    CHANGED=$((CHANGED + 1))
    if [ "$DRY_RUN" -eq 1 ]; then
        printf '  would %s\n' "$*"
    else
        printf '  %s\n' "$*"
    fi
}

# dry — true when running in --dry-run mode. Used as `dry || <mutation>`.
dry() { [ "$DRY_RUN" -eq 1 ]; }

usage() {
    cat <<EOF
$PROG $VERSION — per-project AI artifact transport

usage: $PROG <verb> [args] [options]

verbs:
  init <remote-url>   clone the artifact repo into <git-common-dir>/lundegaard
                      and link its first-level entries into this worktree
  heal                idempotent self-repair of links and the exclude block
  adopt <path>        move an untracked first-level path into the store and
                      link it back
  sync                commit everything in the store, pull --rebase, push
  status              report store, sync and link health (never mutates)
  detach              remove managed links and the exclude block; keep the store

options:
  --dry-run           print the full plan, change nothing
  --quiet             suppress output when nothing changed (heal)
  -m, --message MSG   commit message for sync
  --all-worktrees     detach: also unlink every other worktree of this clone
  -h, --help          this text
  -V, --version       print version
EOF
}

# --- path helpers ----------------------------------------------------------

# canon <path> — fully resolved physical path of an existing path (follows
# symlinks). Fails when the path does not exist or its parent is unreachable.
canon() {
    if [ -d "$1" ]; then
        (cd "$1" && pwd -P)
        return 0
    fi
    cn_p=$1
    cn_n=0
    while [ "$cn_n" -lt 40 ]; do
        cn_d=$(dirname "$cn_p")
        cn_b=$(basename "$cn_p")
        cn_d=$(cd "$cn_d" 2>/dev/null && pwd -P) || return 1
        cn_p="$cn_d/$cn_b"
        if [ -L "$cn_p" ]; then
            cn_t=$(readlink "$cn_p")
            case $cn_t in
                /*) cn_p=$cn_t ;;
                *) cn_p="$cn_d/$cn_t" ;;
            esac
            if [ -d "$cn_p" ]; then
                (cd "$cn_p" && pwd -P)
                return 0
            fi
            cn_n=$((cn_n + 1))
            continue
        fi
        if [ -e "$cn_p" ]; then
            printf '%s\n' "$cn_p"
            return 0
        fi
        return 1
    done
    return 1
}

# lexnorm <abs-path> — resolve . and .. textually (works for missing paths).
lexnorm() {
    lx_in=$1
    lx_out=""
    lx_oifs=$IFS
    IFS=/
    set -f
    for lx_c in $lx_in; do
        case $lx_c in
            '' | .) continue ;;
            ..) lx_out=${lx_out%/*} ;;
            *) lx_out="$lx_out/$lx_c" ;;
        esac
    done
    set +f
    IFS=$lx_oifs
    if [ -z "$lx_out" ]; then
        printf '/\n'
    else
        printf '%s\n' "$lx_out"
    fi
}

# relpath <target-abs> <base-dir-abs> — relative path from base to target.
relpath() {
    rp_t=${1%/}
    rp_b=${2%/}
    if [ -z "$rp_t" ]; then rp_t=/; fi
    if [ "$rp_b" = "/" ]; then rp_b=""; fi
    rp_up=""
    rp_rest=""
    while :; do
        if [ "$rp_t" = "$rp_b" ]; then
            rp_rest=""
            break
        fi
        case $rp_t in
            "$rp_b"/*)
                rp_rest=${rp_t#"$rp_b"/}
                break
                ;;
        esac
        rp_b=$(dirname "$rp_b")
        if [ "$rp_b" = "/" ]; then rp_b=""; fi
        if [ -z "$rp_up" ]; then rp_up=".."; else rp_up="../$rp_up"; fi
    done
    if [ -z "$rp_up" ] && [ -z "$rp_rest" ]; then
        printf '.\n'
    elif [ -z "$rp_up" ]; then
        printf '%s\n' "$rp_rest"
    elif [ -z "$rp_rest" ]; then
        printf '%s\n' "$rp_up"
    else
        printf '%s/%s\n' "$rp_up" "$rp_rest"
    fi
}

# --- store resolution (artifact-store) -------------------------------------

resolve_repo() {
    if ! git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
        die "not inside a git working tree — $PROG needs a git repository (run it from your project)"
    fi
    COMMON_DIR=$(git rev-parse --git-common-dir)
    case $COMMON_DIR in
        /*) ;;
        *) COMMON_DIR="$PWD/$COMMON_DIR" ;;
    esac
    COMMON_DIR=$(cd "$COMMON_DIR" && pwd -P) ||
        die "cannot resolve the git common dir"
    STORE="$COMMON_DIR/lundegaard"
    EXCLUDE_FILE="$COMMON_DIR/info/exclude"
    # The lock is a sibling of the store, not a store-root entry: anything at the
    # store root gets symlinked into the project (D2) and swept up by `sync`'s
    # commit -A. The common dir is shared by every worktree of the clone, so the
    # lock still serializes them all (D5's actual requirement).
    LOCK_DIR="$COMMON_DIR/lundegaard.lock"
    # Same reasoning for the vendored engine: a sibling of the store, never a
    # store-root entry. The common dir is the one location every worktree of the
    # clone can name with `git rev-parse --git-common-dir` (B1).
    VENDORED_ENGINE="$COMMON_DIR/lundegaard.engine.sh"
    WT_ROOT=$(git rev-parse --show-toplevel)
    WT_ROOT=$(cd "$WT_ROOT" && pwd -P) ||
        die "cannot resolve the worktree root"
}

require_store() {
    if [ ! -d "$STORE" ]; then
        die "no artifact store at $STORE — run '$PROG init <remote-url>' first"
    fi
}

# --- locking ---------------------------------------------------------------

release_lock() {
    if [ "$LOCK_HELD" -eq 1 ]; then
        rm -rf "$LOCK_DIR"
        LOCK_HELD=0
    fi
}

cleanup_run() {
    if [ "$INIT_PARTIAL" -eq 1 ] && [ -n "$STORE" ]; then
        rm -rf "$STORE"
        INIT_PARTIAL=0
    fi
    release_lock
}

acquire_lock() {
    if dry; then return 0; fi
    al_i=0
    while [ "$al_i" -lt 10 ]; do
        if mkdir "$LOCK_DIR" 2>/dev/null; then
            LOCK_HELD=1
            trap 'cleanup_run' EXIT
            trap 'cleanup_run; exit 130' INT
            trap 'cleanup_run; exit 143' TERM
            trap 'cleanup_run; exit 129' HUP
            {
                printf 'pid=%s\n' "$$"
                printf 'started=%s\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')"
                printf 'verb=%s\n' "${VERB:-?}"
            } >"$LOCK_DIR/owner" 2>/dev/null || true
            return 0
        fi
        al_i=$((al_i + 1))
        if [ "$al_i" -lt 10 ]; then sleep 1; fi
    done

    al_pid=""
    if [ -f "$LOCK_DIR/owner" ]; then
        al_pid=$(sed -n 's/^pid=//p' "$LOCK_DIR/owner" 2>/dev/null || true)
    fi
    if [ -n "$al_pid" ] && ! kill -0 "$al_pid" 2>/dev/null; then
        die "store lock $LOCK_DIR is held by pid $al_pid, which is no longer running.
If no other $PROG is active, remove it: rm -rf '$LOCK_DIR'"
    fi
    die "could not acquire the store lock $LOCK_DIR (held by pid ${al_pid:-unknown}); another $PROG run is in progress"
}

# --- store listing (artifact-linking) --------------------------------------

# store_entries — first-level store entries except .git, one per line, sorted.
store_entries() {
    if [ ! -d "$STORE" ]; then return 0; fi
    (
        cd "$STORE" || exit 0
        for se_e in * .[!.]* ..?*; do
            if [ ! -e "$se_e" ] && [ ! -L "$se_e" ]; then continue; fi
            if [ "$se_e" = ".git" ]; then continue; fi
            printf '%s\n' "$se_e"
        done
    ) | LC_ALL=C sort
}

# --- exclude block (D4) ----------------------------------------------------

has_block() {
    [ -f "$EXCLUDE_FILE" ] && grep -Fqx "$EXCL_BEGIN" "$EXCLUDE_FILE" 2>/dev/null
}

# read_managed — names currently listed inside the managed block.
read_managed() {
    if [ ! -f "$EXCLUDE_FILE" ]; then return 0; fi
    rd_inside=0
    while IFS= read -r rd_line || [ -n "$rd_line" ]; do
        if [ "$rd_line" = "$EXCL_BEGIN" ]; then
            rd_inside=1
            continue
        fi
        if [ "$rd_inside" -eq 1 ] && [ "$rd_line" = "$EXCL_END" ]; then
            rd_inside=0
            continue
        fi
        if [ "$rd_inside" -eq 1 ]; then
            case $rd_line in
                '' | '#'*) continue ;;
            esac
            rd_line=${rd_line#/}
            case $rd_line in
                '\'*) rd_line=${rd_line#\\} ;;
            esac
            printf '%s\n' "$rd_line"
        fi
    done <"$EXCLUDE_FILE"
}

# emit_block <newline-separated-names>
emit_block() {
    printf '%s\n%s\n' "$EXCL_BEGIN" "$EXCL_NOTE"
    printf '%s\n' "$1" | while IFS= read -r eb_n; do
        if [ -z "$eb_n" ]; then continue; fi
        case $eb_n in
            '#'* | '!'*) printf '/\\%s\n' "$eb_n" ;;
            *) printf '/%s\n' "$eb_n" ;;
        esac
    done
    printf '%s\n' "$EXCL_END"
}

# write_exclude <newline-separated-names> — rewrite the managed block in place,
# preserving every byte outside the markers. Empty input removes the block.
write_exclude() {
    we_entries=$1
    if [ -z "$we_entries" ]; then
        remove_exclude
        return 0
    fi
    we_dir=$(dirname "$EXCLUDE_FILE")
    if [ ! -d "$we_dir" ]; then mkdir -p "$we_dir"; fi
    we_tmp="$EXCLUDE_FILE.lnd-tmp.$$"

    if [ -f "$EXCLUDE_FILE" ] && has_block; then
        : >"$we_tmp"
        we_inside=0
        while :; do
            if IFS= read -r we_line; then
                we_nl=1
            else
                we_nl=0
                if [ -z "$we_line" ]; then break; fi
            fi

            if [ "$we_line" = "$EXCL_BEGIN" ]; then
                we_inside=1
                emit_block "$we_entries" >>"$we_tmp"
            elif [ "$we_inside" -eq 1 ]; then
                if [ "$we_line" = "$EXCL_END" ]; then we_inside=0; fi
            else
                printf '%s' "$we_line" >>"$we_tmp"
                if [ "$we_nl" -eq 1 ]; then printf '\n' >>"$we_tmp"; fi
            fi

            if [ "$we_nl" -eq 0 ]; then break; fi
        done <"$EXCLUDE_FILE"
    else
        # Prepending lets an unterminated user-authored final line remain exact.
        emit_block "$we_entries" >"$we_tmp"
        if [ -f "$EXCLUDE_FILE" ]; then cat "$EXCLUDE_FILE" >>"$we_tmp"; fi
    fi
    mv "$we_tmp" "$EXCLUDE_FILE"
}

remove_exclude() {
    if [ ! -f "$EXCLUDE_FILE" ]; then return 0; fi
    if ! has_block; then return 0; fi
    rx_tmp="$EXCLUDE_FILE.lnd-tmp.$$"
    : >"$rx_tmp"
    rx_inside=0
    while :; do
        if IFS= read -r rx_line; then
            rx_nl=1
        else
            rx_nl=0
            if [ -z "$rx_line" ]; then break; fi
        fi

        if [ "$rx_line" = "$EXCL_BEGIN" ]; then
            rx_inside=1
        elif [ "$rx_inside" -eq 1 ]; then
            if [ "$rx_line" = "$EXCL_END" ]; then rx_inside=0; fi
        else
            printf '%s' "$rx_line" >>"$rx_tmp"
            if [ "$rx_nl" -eq 1 ]; then printf '\n' >>"$rx_tmp"; fi
        fi

        if [ "$rx_nl" -eq 0 ]; then break; fi
    done <"$EXCLUDE_FILE"
    mv "$rx_tmp" "$EXCLUDE_FILE"
}

# sync_exclude <newline-separated-names> — rewrite only when the block differs.
sync_exclude() {
    sx_want=$1
    sx_have=$(read_managed)
    if [ "$sx_want" = "$sx_have" ]; then
        if [ -z "$sx_want" ] || has_block; then
            return 0
        fi
    fi
    if [ -z "$sx_want" ]; then
        report "remove managed block from $EXCLUDE_FILE"
    else
        report "update managed block in $EXCLUDE_FILE"
    fi
    dry || write_exclude "$sx_want"
}

# --- link helpers (D2, D3) -------------------------------------------------

# link_into_store <path> — true when <path> is a symlink resolving into the
# store (textually, so broken links still count as ours).
link_into_store() {
    lis_t=$(readlink "$1" 2>/dev/null) || return 1
    case $lis_t in
        /*) lis_abs=$lis_t ;;
        *) lis_abs="$(dirname "$1")/$lis_t" ;;
    esac
    lis_abs=$(lexnorm "$lis_abs")
    case $lis_abs in
        "$STORE" | "$STORE"/*) return 0 ;;
    esac
    return 1
}

# host_tracks <name> — true when the host repository tracks this first-level path.
host_tracks() {
    [ -n "$(git -C "$WT_ROOT" ls-files -- "$1" 2>/dev/null)" ]
}

# quarantine <name> — rename a foreign path out of the way, never delete.
quarantine() {
    qr_name=$1
    qr_ts=$(date '+%Y%m%d%H%M%S')
    qr_new="$qr_name.quarantined-$qr_ts"
    qr_i=0
    while [ -e "$WT_ROOT/$qr_new" ] || [ -L "$WT_ROOT/$qr_new" ]; do
        qr_i=$((qr_i + 1))
        qr_new="$qr_name.quarantined-$qr_ts-$qr_i"
    done
    report "QUARANTINE $qr_name -> $qr_new (pre-existing, not deleted)"
    dry || mv "$WT_ROOT/$qr_name" "$WT_ROOT/$qr_new"
}

# skip_tracked <name> — refuse to move a path the host repository tracks.
# Quarantining tracked content would show up as a deletion in the customer's
# repository, which this tool must never cause.
skip_tracked() {
    if ! host_tracks "$1"; then return 1; fi
    warn "skipped '$1': the host repository tracks it, and the store also provides an
  entry with that name. Nothing was moved — customer content wins. Rename the store
  entry ($STORE/$1) or drop it from the store to resolve the collision."
    return 0
}

# ensure_link <name> — make $WT_ROOT/<name> a correct relative symlink to the
# store entry, quarantining whatever foreign thing sits there.
ensure_link() {
    el_name=$1
    el_src="$STORE/$el_name"
    el_dst="$WT_ROOT/$el_name"
    el_want=$(relpath "$el_src" "$WT_ROOT")

    if [ -L "$el_dst" ]; then
        el_have=$(canon "$el_dst" 2>/dev/null || true)
        el_expect=$(canon "$el_src" 2>/dev/null || true)
        if [ -n "$el_have" ] && [ "$el_have" = "$el_expect" ]; then
            return 0
        fi
        if link_into_store "$el_dst"; then
            report "relink $el_name -> $el_want"
            dry || {
                rm -f "$el_dst"
                ln -s "$el_want" "$el_dst"
            }
            return 0
        fi
        if skip_tracked "$el_name"; then return 0; fi
        quarantine "$el_name"
    elif [ -e "$el_dst" ]; then
        if skip_tracked "$el_name"; then return 0; fi
        quarantine "$el_name"
    fi

    report "link $el_name -> $el_want"
    dry || ln -s "$el_want" "$el_dst"
}

# unlink_managed <name> — remove a managed link (only ever a symlink into the
# store); report anything else and leave it alone.
unlink_managed() {
    um_name=$1
    um_dst="$WT_ROOT/$um_name"
    if [ ! -L "$um_dst" ]; then
        # A real path here was never ours — heal already warned about the
        # collision if the host tracks it.
        if [ -e "$um_dst" ] && ! host_tracks "$um_name"; then
            warn "left $um_name alone: not a symlink into the store"
        fi
        return 0
    fi
    if host_tracks "$um_name"; then
        warn "left $um_name alone: the host repository tracks it"
        return 0
    fi
    if link_into_store "$um_dst"; then
        report "unlink $um_name"
        dry || rm -f "$um_dst"
        return 0
    fi
    warn "left $um_name alone: symlink does not point into the store"
    return 0
}

# --- vendored engine (artifact-bootstrap) ----------------------------------

# vendored_version — the VERSION of the vendored copy, read as text. Never
# executes the copy: a corrupt one must still be replaceable (B3).
vendored_version() {
    if [ ! -f "$VENDORED_ENGINE" ]; then return 0; fi
    sed -n 's/^VERSION=//p' "$VENDORED_ENGINE" 2>/dev/null | sed -n '1p'
}

# write_vendored — copy the running engine over the vendored path atomically, so
# a concurrent worktree-init never sees a half-written script.
write_vendored() {
    wv_tmp="$VENDORED_ENGINE.lnd-tmp.$$"
    cp "$SELF" "$wv_tmp"
    chmod 755 "$wv_tmp"
    mv "$wv_tmp" "$VENDORED_ENGINE"
}

# ensure_vendored — create the vendored copy when missing, refresh it when its
# version differs from ours (upgrade or downgrade), otherwise change nothing.
ensure_vendored() {
    if [ ! -r "$SELF" ]; then
        warn "cannot vendor the engine: this script is not readable at $SELF"
        return 0
    fi
    if [ -e "$VENDORED_ENGINE" ] && [ ! -f "$VENDORED_ENGINE" ]; then
        warn "not vendoring the engine: $VENDORED_ENGINE exists and is not a regular file"
        return 0
    fi
    if [ -f "$VENDORED_ENGINE" ] && [ -x "$VENDORED_ENGINE" ]; then
        ev_have=$(vendored_version)
        if [ "$ev_have" = "$VERSION" ]; then return 0; fi
        report "refresh the vendored engine at $VENDORED_ENGINE (${ev_have:-unreadable version} -> $VERSION)"
    else
        report "vendor the engine $VERSION to $VENDORED_ENGINE"
    fi
    dry || write_vendored
}

remove_vendored() {
    if [ ! -e "$VENDORED_ENGINE" ] && [ ! -L "$VENDORED_ENGINE" ]; then return 0; fi
    report "remove the vendored engine at $VENDORED_ENGINE"
    dry || rm -f "$VENDORED_ENGINE"
}

# --- heal (3.2) ------------------------------------------------------------

do_heal() {
    dh_entries=$(store_entries)

    # Drop links whose store entry disappeared. The managed block is the record
    # of what we linked last time.
    dh_managed=$(read_managed)
    if [ -n "$dh_managed" ]; then
        dh_oifs=$IFS
        IFS='
'
        set -f
        # shellcheck disable=SC2086
        set -- $dh_managed
        set +f
        IFS=$dh_oifs
        for dh_old in "$@"; do
            if printf '%s\n' "$dh_entries" | grep -Fqx -- "$dh_old"; then continue; fi
            unlink_managed "$dh_old"
        done
    fi

    # The block is shared by every worktree, so once one heal has dropped a
    # removed entry from it, the other worktrees' links are no longer listed.
    # Also drop any root symlink that points at exactly $STORE/<its own name>
    # when that entry is gone.
    for dh_p in "$WT_ROOT"/* "$WT_ROOT"/.[!.]* "$WT_ROOT"/..?*; do
        if [ ! -L "$dh_p" ]; then continue; fi
        dh_n=${dh_p##*/}
        if printf '%s\n' "$dh_entries" | grep -Fqx -- "$dh_n"; then continue; fi
        dh_t=$(readlink "$dh_p")
        case $dh_t in
            /*) ;;
            *) dh_t="$WT_ROOT/$dh_t" ;;
        esac
        if [ "$(lexnorm "$dh_t")" != "$STORE/$dh_n" ]; then continue; fi
        unlink_managed "$dh_n"
    done

    if [ -n "$dh_entries" ]; then
        dh_oifs=$IFS
        IFS='
'
        set -f
        # shellcheck disable=SC2086
        set -- $dh_entries
        set +f
        IFS=$dh_oifs
        for dh_e in "$@"; do
            ensure_link "$dh_e"
        done
    fi

    sync_exclude "$dh_entries"
    ensure_vendored
}

heal_summary() {
    hs_n=$1
    if [ "$CHANGED" -eq 0 ]; then
        info "$PROG: healthy — $hs_n link(s) up to date in $WT_ROOT"
    elif dry; then
        say "$PROG: $CHANGED change(s) planned (dry run, nothing written)"
    else
        say "$PROG: healed — $CHANGED change(s) in $WT_ROOT"
    fi
}

cmd_heal() {
    resolve_repo
    acquire_lock
    require_store
    do_heal
    ch_n=$(store_entries | grep -c . || true)
    release_lock
    heal_summary "$ch_n"
}

# --- init (3.1) ------------------------------------------------------------

cmd_init() {
    ci_url=${1:-}
    if [ -z "$ci_url" ]; then
        usage >&2
        die "init needs the artifact repository remote URL"
    fi
    resolve_repo
    acquire_lock
    if [ -e "$STORE" ] || [ -L "$STORE" ]; then
        die "an artifact store already exists at $STORE — use '$PROG status' or '$PROG heal'"
    fi

    if dry; then
        say "$PROG: init plan"
        report "clone $ci_url -> $STORE"
        report "link every post-clone first-level store entry (except .git) into $WT_ROOT"
        report "generate the managed block in $EXCLUDE_FILE from that store listing"
        report "vendor the engine $VERSION to $VENDORED_ENGINE"
        release_lock
        say "$PROG: $CHANGED change(s) planned (dry run, nothing written)"
        return 0
    fi

    say "$PROG: cloning $ci_url"
    INIT_PARTIAL=1
    if ! git clone -- "$ci_url" "$STORE"; then
        die "clone failed — no store was created"
    fi
    INIT_PARTIAL=0
    CHANGED=$((CHANGED + 1))
    do_heal
    ci_n=$(store_entries | grep -c . || true)
    release_lock
    say "$PROG: store ready at $STORE"
    if [ "$ci_n" = "0" ]; then
        say "$PROG: the store is empty — add artifacts inside $STORE (or use '$PROG adopt <path>')"
    fi
}

# --- adopt (3.3) -----------------------------------------------------------

cmd_adopt() {
    ca_arg=${1:-}
    if [ -z "$ca_arg" ]; then
        usage >&2
        die "adopt needs a path"
    fi
    resolve_repo

    # Only first-level entries of the current worktree root.
    ca_abs=$ca_arg
    case $ca_abs in
        /*) ;;
        *) ca_abs="$PWD/$ca_abs" ;;
    esac
    ca_abs=$(lexnorm "$ca_abs")
    ca_abs=${ca_abs%/}
    ca_name=$(basename "$ca_abs")
    ca_parent=$(dirname "$ca_abs")
    ca_parent=$(cd "$ca_parent" 2>/dev/null && pwd -P) ||
        die "cannot resolve $ca_arg"
    if [ "$ca_parent" != "$WT_ROOT" ]; then
        die "adopt only takes first-level entries of the worktree root ($WT_ROOT); '$ca_arg' lives in $ca_parent"
    fi
    ca_path="$WT_ROOT/$ca_name"

    acquire_lock
    require_store
    if [ ! -e "$ca_path" ] && [ ! -L "$ca_path" ]; then
        die "$ca_name does not exist in $WT_ROOT"
    fi
    if [ -L "$ca_path" ] && link_into_store "$ca_path"; then
        die "$ca_name is already a managed link into the store"
    fi
    if [ -e "$STORE/$ca_name" ] || [ -L "$STORE/$ca_name" ]; then
        die "the store already contains '$ca_name' — resolve the collision by hand in $STORE"
    fi
    if [ "$ca_name" = ".git" ]; then
        die "refusing to adopt .git"
    fi
    if [ -n "$(git -C "$WT_ROOT" ls-files -- "$ca_name" 2>/dev/null)" ]; then
        die "'$ca_name' is tracked by the host repository — tracked content belongs to the customer repo and adopting it would require a deletion commit there"
    fi

    say "$PROG: adopting $ca_name"
    if dry; then
        report "move $ca_path -> $STORE/$ca_name"
        report "link $ca_name -> $(relpath "$STORE/$ca_name" "$WT_ROOT")"
        report "add /$ca_name to the managed block in $EXCLUDE_FILE"
        release_lock
        say "$PROG: $CHANGED change(s) planned (dry run, nothing written)"
        return 0
    fi

    report "move $ca_path -> $STORE/$ca_name"
    mv "$ca_path" "$STORE/$ca_name"
    ensure_link "$ca_name"
    sync_exclude "$(store_entries)"
    release_lock
    say "$PROG: adopted $ca_name — commit it with '$PROG sync'"
}

# --- sync (3.4) ------------------------------------------------------------

store_git() { git -C "$STORE" "$@"; }

store_branch() { store_git symbolic-ref --quiet --short HEAD 2>/dev/null || printf 'HEAD\n'; }

store_upstream() {
    su_branch=$(store_git symbolic-ref --quiet --short HEAD 2>/dev/null || true)
    [ -n "$su_branch" ] || return 0
    su_remote=$(store_git config --get "branch.$su_branch.remote" 2>/dev/null || true)
    su_merge=$(store_git config --get "branch.$su_branch.merge" 2>/dev/null || true)
    [ -n "$su_remote" ] && [ -n "$su_merge" ] || return 0
    su_name=${su_merge#refs/heads/}
    if [ "$su_remote" = "." ]; then
        printf '%s\n' "$su_name"
    else
        printf '%s/%s\n' "$su_remote" "$su_name"
    fi
}

store_dirty_count() { store_git status --porcelain --untracked-files=all | grep -c . || true; }

store_rebase_active() {
    sra_git=$(store_git rev-parse --absolute-git-dir 2>/dev/null || true)
    [ -n "$sra_git" ] || return 1
    [ -d "$sra_git/rebase-merge" ] || [ -d "$sra_git/rebase-apply" ]
}

sync_rebase_stop() {
    warn "$1"
    sr_conf=$(store_git diff --name-only --diff-filter=U 2>/dev/null || true)
    if [ -n "$sr_conf" ]; then
        warn "conflicted paths:"
        printf '%s\n' "$sr_conf" | sed 's/^/  /' >&2
    fi
    warn "inspect and resolve it: git -C '$STORE' status"
    warn "then finish it:          git -C '$STORE' rebase --continue"
    warn "or abandon it:           git -C '$STORE' rebase --abort"
    warn "run '$PROG sync' again only after the rebase has finished or been aborted"
    exit 1
}

cmd_sync() {
    cs_msg=${SYNC_MESSAGE:-}
    resolve_repo
    acquire_lock
    require_store

    if store_rebase_active; then
        sync_rebase_stop "a rebase is already in progress in the artifact store: $STORE"
    fi

    cs_dirty=$(store_dirty_count)
    cs_has_head=0
    if store_git rev-parse --verify --quiet HEAD >/dev/null 2>&1; then cs_has_head=1; fi

    cs_branch=$(store_git symbolic-ref --quiet --short HEAD 2>/dev/null || true)
    cs_up=$(store_upstream)
    cs_up_remote=""
    cs_up_branch=""
    if [ -n "$cs_up" ]; then
        cs_up_remote=$(store_git config --get "branch.$cs_branch.remote" 2>/dev/null || true)
        cs_up_merge=$(store_git config --get "branch.$cs_branch.merge" 2>/dev/null || true)
        cs_up_branch=${cs_up_merge#refs/heads/}
    fi
    cs_remotes=$(store_git remote 2>/dev/null || true)
    cs_remote=""
    cs_remote_branch=$cs_branch
    # An unborn branch cannot use pull, but its configured target still wins.
    if [ "$cs_has_head" -eq 0 ] && [ -n "$cs_up" ]; then
        cs_remote=$cs_up_remote
        cs_remote_branch=$cs_up_branch
        if [ "$cs_remote" = "." ]; then
            die "the unborn store branch tracks a local branch; create its first commit before syncing $STORE"
        fi
        cs_up=""
    fi
    if [ -z "$cs_up" ] && [ -z "$cs_remote" ]; then
        if printf '%s\n' "$cs_remotes" | grep -Fqx origin; then
            cs_remote=origin
        else
            cs_remote_count=$(printf '%s\n' "$cs_remotes" | grep -c . || true)
            if [ "$cs_remote_count" -eq 1 ]; then
                cs_remote=$cs_remotes
            elif [ "$cs_remote_count" -gt 1 ]; then
                die "the store branch has no upstream and multiple remotes are configured; configure an upstream before syncing $STORE"
            fi
        fi
    fi
    if [ -z "$cs_branch" ] && { [ -n "$cs_up" ] || [ -n "$cs_remote" ]; }; then
        die "the artifact store is on a detached HEAD; check out a branch before syncing $STORE"
    fi

    if [ -z "$cs_msg" ]; then
        cs_msg="artifacts: sync $(date '+%Y-%m-%d %H:%M:%S')"
    fi

    if dry; then
        say "$PROG: sync plan for $STORE"
        if [ "$cs_dirty" != "0" ]; then
            report "commit $cs_dirty change(s) with message: $cs_msg"
        fi
        if [ -n "$cs_up" ]; then
            report "pull --rebase from $cs_up"
            report "push if commits remain ahead of $cs_up"
        elif [ -n "$cs_remote" ]; then
            report "fetch $cs_remote"
            report "rebase onto $cs_remote/$cs_remote_branch if that remote branch exists"
            report "push -u $cs_remote $cs_branch:$cs_remote_branch"
        else
            say "$PROG: the store has no remote; any commit would remain local"
        fi
        release_lock
        say "$PROG: $CHANGED change(s) planned (dry run, nothing written)"
        return 0
    fi

    cs_committed=0
    if [ "$cs_dirty" != "0" ]; then
        report "commit $cs_dirty change(s)"
        store_git add -A
        store_git commit -q -m "$cs_msg"
        cs_committed=1
        cs_has_head=1
    fi

    if [ -z "$cs_up" ] && [ -z "$cs_remote" ]; then
        cs_final=$(store_git rev-parse --short HEAD 2>/dev/null || true)
        release_lock
        if [ "$cs_committed" -eq 1 ]; then
            say "$PROG: committed $cs_final locally; the store has no remote, so nothing was pushed"
        elif [ "$cs_has_head" -eq 0 ]; then
            say "$PROG: the store is empty and has no commits or remote — nothing to sync"
        else
            say "$PROG: the store has no remote — existing commits remain local"
        fi
        return 0
    fi

    if [ -n "$cs_up" ]; then
        cs_before=$(store_git rev-parse HEAD)
        report "pull --rebase from $cs_up"
        if ! store_git pull --rebase --quiet; then
            if store_rebase_active || [ -n "$(store_git diff --name-only --diff-filter=U 2>/dev/null || true)" ]; then
                sync_rebase_stop "rebase stopped in the artifact store: $STORE"
            fi
            die "pull --rebase from $cs_up failed — the store is at $STORE"
        fi

        cs_after=$(store_git rev-parse HEAD)
        cs_ahead=$(store_git rev-list --count '@{u}..HEAD' 2>/dev/null || printf '0')
        if [ "$cs_ahead" != "0" ]; then
            report "push $cs_branch:$cs_up_branch to $cs_up_remote"
            if ! store_git push --quiet "$cs_up_remote" "$cs_branch:$cs_up_branch"; then
                die "push to $cs_up failed — the store is at $STORE"
            fi
            cs_final=$(store_git rev-parse --short HEAD)
            release_lock
            say "$PROG: pushed $cs_final to $cs_up"
        else
            release_lock
            if [ "$cs_before" != "$cs_after" ]; then
                say "$PROG: updated the local store from $cs_up — nothing needed pushing"
            else
                say "$PROG: already in sync — remote checked, nothing to commit or push"
            fi
        fi
        return 0
    fi

    cs_before=""
    if [ "$cs_has_head" -eq 1 ]; then cs_before=$(store_git rev-parse HEAD); fi
    report "fetch $cs_remote"
    if ! store_git fetch --quiet "$cs_remote"; then
        die "fetch from $cs_remote failed — the store is at $STORE"
    fi
    cs_remote_ref="refs/remotes/$cs_remote/$cs_remote_branch"
    cs_had_remote_branch=0
    if store_git show-ref --verify --quiet "$cs_remote_ref"; then
        cs_had_remote_branch=1
        if [ "$cs_has_head" -eq 0 ]; then
            report "initialize $cs_branch from $cs_remote/$cs_remote_branch"
            store_git reset --hard -q "$cs_remote/$cs_remote_branch"
            cs_has_head=1
        else
            report "rebase onto $cs_remote/$cs_remote_branch"
            if ! store_git rebase --quiet "$cs_remote/$cs_remote_branch"; then
                if store_rebase_active || [ -n "$(store_git diff --name-only --diff-filter=U 2>/dev/null || true)" ]; then
                    sync_rebase_stop "rebase stopped in the artifact store: $STORE"
                fi
                die "rebase onto $cs_remote/$cs_remote_branch failed — the store is at $STORE"
            fi
        fi
    elif [ "$cs_has_head" -eq 0 ]; then
        release_lock
        say "$PROG: the local store and $cs_remote/$cs_remote_branch are both empty — nothing to sync"
        return 0
    fi

    cs_after=$(store_git rev-parse HEAD)
    report "push -u $cs_remote $cs_branch:$cs_remote_branch"
    if ! store_git push --quiet -u "$cs_remote" "$cs_branch:$cs_remote_branch"; then
        die "push to $cs_remote/$cs_remote_branch failed — the store is at $STORE"
    fi
    cs_final=$(store_git rev-parse --short HEAD)
    release_lock
    if [ "$cs_had_remote_branch" -eq 1 ] && [ -z "$cs_before" ]; then
        say "$PROG: initialized from $cs_remote/$cs_remote_branch and configured it as upstream"
    elif [ "$cs_had_remote_branch" -eq 1 ] && [ "$cs_before" != "$cs_after" ] && [ "$cs_committed" -eq 0 ]; then
        say "$PROG: updated from $cs_remote/$cs_remote_branch and configured it as upstream — nothing needed pushing"
    else
        say "$PROG: pushed $cs_final to $cs_remote/$cs_remote_branch and configured the upstream"
    fi
}

# --- status (3.5) ----------------------------------------------------------

cmd_status() {
    resolve_repo

    say "$PROG $VERSION"
    say "  worktree : $WT_ROOT"
    say "  store    : $STORE"

    if [ ! -d "$STORE" ]; then
        say "  state    : no store initialized — run '$PROG init <remote-url>'"
        return 0
    fi

    if [ ! -f "$VENDORED_ENGINE" ] || [ ! -x "$VENDORED_ENGINE" ]; then
        say "  engine   : not vendored at $VENDORED_ENGINE -> run '$PROG heal' to restore it"
    else
        ct_vend=$(vendored_version)
        if [ "$ct_vend" = "$VERSION" ]; then
            say "  engine   : vendored $ct_vend at $VENDORED_ENGINE"
        else
            say "  engine   : vendored ${ct_vend:-unreadable version} at $VENDORED_ENGINE differs from the running $VERSION -> run '$PROG heal' to refresh"
        fi
    fi

    ct_dirty=$(store_dirty_count)
    ct_up=$(store_upstream)
    ct_branch=$(store_branch)
    ct_compare=""
    ct_compare_kind=""
    if [ -n "$ct_up" ] && store_git rev-parse --verify --quiet '@{u}' >/dev/null 2>&1; then
        ct_compare='@{u}'
        ct_compare_kind=upstream
    elif [ -z "$ct_up" ] && [ "$ct_branch" != "HEAD" ]; then
        if store_git show-ref --verify --quiet "refs/remotes/origin/$ct_branch"; then
            ct_compare="origin/$ct_branch"
            ct_compare_kind=tracking
        else
            ct_candidates=""
            for ct_remote in $(store_git remote 2>/dev/null || true); do
                if store_git show-ref --verify --quiet "refs/remotes/$ct_remote/$ct_branch"; then
                    ct_candidates="${ct_candidates}${ct_candidates:+
}$ct_remote/$ct_branch"
                fi
            done
            if [ "$(printf '%s\n' "$ct_candidates" | grep -c . || true)" -eq 1 ]; then
                ct_compare=$ct_candidates
                ct_compare_kind=tracking
            fi
        fi
    fi

    ct_ahead=unknown
    ct_behind=unknown
    if [ -n "$ct_compare" ]; then
        ct_ahead=$(store_git rev-list --count "$ct_compare..HEAD" 2>/dev/null || printf 'unknown')
        ct_behind=$(store_git rev-list --count "HEAD..$ct_compare" 2>/dev/null || printf 'unknown')
    fi

    say "  branch   : $ct_branch${ct_up:+ (upstream $ct_up)}"
    if [ -z "$ct_up" ]; then
        say "  remote   : no upstream configured for $ct_branch"
    elif [ -z "$ct_compare" ]; then
        say "  remote   : configured upstream $ct_up is not available locally"
    fi
    say "  dirty    : $ct_dirty file(s) uncommitted"
    if [ "$ct_compare_kind" = tracking ]; then
        say "  unpushed : $ct_ahead commit(s) relative to $ct_compare (as of the last fetch)"
        say "  behind   : $ct_behind commit(s) relative to $ct_compare (status never fetches)"
    elif [ "$ct_compare_kind" = upstream ]; then
        say "  unpushed : $ct_ahead commit(s)"
        say "  behind   : $ct_behind commit(s) (as of the last fetch; status never fetches)"
    else
        say "  unpushed : unknown (no usable upstream/tracking ref)"
        say "  behind   : unknown (status never fetches)"
    fi

    ct_entries=$(store_entries)
    ct_total=$(printf '%s\n' "$ct_entries" | grep -c . || true)
    say "  links    : $ct_total managed entry(ies)"

    ct_bad=0
    if [ -n "$ct_entries" ]; then
        ct_oifs=$IFS
        IFS='
'
        set -f
        # shellcheck disable=SC2086
        set -- $ct_entries
        set +f
        IFS=$ct_oifs
        for ct_e in "$@"; do
            ct_dst="$WT_ROOT/$ct_e"
            if [ ! -L "$ct_dst" ] && [ ! -e "$ct_dst" ]; then
                say "    MISSING      $ct_e"
                ct_bad=$((ct_bad + 1))
            elif [ ! -L "$ct_dst" ]; then
                if host_tracks "$ct_e"; then
                    say "    COLLISION    $ct_e (tracked by the host repo; the store entry cannot be linked)"
                else
                    say "    NOT-A-LINK   $ct_e (real file or directory in the way)"
                fi
                ct_bad=$((ct_bad + 1))
            else
                ct_have=$(canon "$ct_dst" 2>/dev/null || true)
                ct_expect=$(canon "$STORE/$ct_e" 2>/dev/null || true)
                if [ -z "$ct_have" ] || [ "$ct_have" != "$ct_expect" ]; then
                    say "    WRONG-TARGET $ct_e"
                    ct_bad=$((ct_bad + 1))
                fi
            fi
        done
    fi
    if [ "$ct_bad" -eq 0 ] && [ "$ct_total" != "0" ]; then
        say "    all links healthy in this worktree"
    fi
    if [ "$ct_bad" -ne 0 ]; then
        say "    -> run '$PROG heal' to repair"
    fi

    if ! has_block && [ "$ct_total" != "0" ]; then
        say "  exclude  : managed block MISSING from $EXCLUDE_FILE -> run '$PROG heal'"
    fi

    ct_q=$(
        cd "$WT_ROOT" 2>/dev/null || exit 0
        for ct_f in *.quarantined-* .*.quarantined-*; do
            if [ -e "$ct_f" ] || [ -L "$ct_f" ]; then printf '%s\n' "$ct_f"; fi
        done
    )
    if [ -n "$ct_q" ]; then
        say "  quarantine leftovers in this worktree:"
        printf '%s\n' "$ct_q" | sed 's/^/    /'
    fi

    ct_susp=$(
        printf '%s\n' "$ct_entries" |
            grep -Ex '(README|readme|README\.md|readme\.md|LICENSE|LICENSE\.md|\.gitignore|\.gitattributes)' || true
    )
    if [ -n "$ct_susp" ]; then
        say "  WARNING: the store root should be payload-only; these entries get symlinked"
        say "           into the project root and probably do not belong there:"
        printf '%s\n' "$ct_susp" | sed 's/^/    /'
    fi

    if [ "$ct_dirty" != "0" ] || { [ "$ct_ahead" != "0" ] && [ "$ct_ahead" != "unknown" ]; }; then
        say "  -> unsynced artifact work: run '$PROG sync'"
    fi
    return 0
}

# --- detach (3.6) ------------------------------------------------------------

detach_worktree() {
    dw_root=$1
    dw_names=$2
    dw_save=$WT_ROOT
    WT_ROOT=$dw_root
    say "$PROG: unlinking in $dw_root"
    dw_oifs=$IFS
    IFS='
'
    set -f
    # shellcheck disable=SC2086
    set -- $dw_names
    set +f
    IFS=$dw_oifs
    for dw_n in "$@"; do
        unlink_managed "$dw_n"
    done
    WT_ROOT=$dw_save
}

cmd_detach() {
    resolve_repo
    acquire_lock
    require_store

    dt_names=$(read_managed)
    if [ -z "$dt_names" ]; then
        dt_names=$(store_entries)
    fi
    if [ -z "$dt_names" ]; then
        remove_vendored
        release_lock
        if [ "$CHANGED" -eq 0 ]; then
            say "$PROG: nothing managed here — no links or exclude block to remove"
        elif dry; then
            say "$PROG: $CHANGED change(s) planned (dry run, nothing written)"
        else
            say "$PROG: detached — $CHANGED change(s); the store at $STORE is untouched ('$PROG heal' restores everything)"
        fi
        return 0
    fi

    detach_worktree "$WT_ROOT" "$dt_names"

    dt_others=$(
        git worktree list --porcelain 2>/dev/null |
            sed -n 's/^worktree //p' || true
    )
    dt_rest=""
    if [ -n "$dt_others" ]; then
        dt_oifs=$IFS
        IFS='
'
        set -f
        # shellcheck disable=SC2086
        set -- $dt_others
        set +f
        IFS=$dt_oifs
        for dt_w in "$@"; do
            dt_wp=$(cd "$dt_w" 2>/dev/null && pwd -P) || dt_wp=""
            if [ -z "$dt_wp" ] || [ "$dt_wp" = "$WT_ROOT" ]; then continue; fi
            if [ "$ALL_WORKTREES" -eq 1 ]; then
                detach_worktree "$dt_wp" "$dt_names"
            else
                dt_rest="${dt_rest}${dt_rest:+
}$dt_wp"
            fi
        done
    fi

    sync_exclude ""
    remove_vendored

    release_lock

    if [ -n "$dt_rest" ]; then
        say "$PROG: other worktrees of this clone still carry managed links:"
        printf '%s\n' "$dt_rest" | sed 's/^/    /'
        say "         re-run with --all-worktrees to unlink them too"
    fi
    if dry; then
        say "$PROG: $CHANGED change(s) planned (dry run, nothing written)"
    else
        say "$PROG: detached — $CHANGED change(s); the store at $STORE is untouched ('$PROG heal' restores everything)"
    fi
}

# --- dispatch (2.1) --------------------------------------------------------

VERB=""
SYNC_MESSAGE=""
ARG1=""

main() {
    if [ "$#" -eq 0 ]; then
        usage >&2
        exit 1
    fi

    while [ "$#" -gt 0 ]; do
        case $1 in
            --dry-run | -n)
                DRY_RUN=1
                ;;
            --quiet | -q)
                QUIET=1
                ;;
            --all-worktrees)
                ALL_WORKTREES=1
                ;;
            -m | --message)
                if [ "$#" -lt 2 ]; then die "$1 needs a value"; fi
                shift
                SYNC_MESSAGE=$1
                ;;
            -h | --help | help)
                usage
                exit 0
                ;;
            -V | --version)
                say "$PROG $VERSION"
                exit 0
                ;;
            --)
                shift
                while [ "$#" -gt 0 ]; do
                    if [ -z "$VERB" ]; then VERB=$1; elif [ -z "$ARG1" ]; then ARG1=$1; fi
                    shift
                done
                break
                ;;
            -*)
                usage >&2
                die "unknown option: $1"
                ;;
            *)
                if [ -z "$VERB" ]; then
                    VERB=$1
                elif [ -z "$ARG1" ]; then
                    ARG1=$1
                else
                    usage >&2
                    die "unexpected argument: $1"
                fi
                ;;
        esac
        shift
    done

    if [ -z "$VERB" ]; then
        usage >&2
        die "no verb given"
    fi

    case $VERB in
        init) cmd_init "$ARG1" ;;
        heal) cmd_heal ;;
        adopt) cmd_adopt "$ARG1" ;;
        sync) cmd_sync ;;
        status) cmd_status ;;
        detach) cmd_detach ;;
        *)
            usage >&2
            die "unknown verb: $VERB"
            ;;
    esac
}

main "$@"
